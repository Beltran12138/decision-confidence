"""Bundle the Cloudflare Worker: docs/assets/hl.js + worker/src/worker.js -> worker/dist/worker.js.

One ES module, no dependencies, so it can be pasted into the Cloudflare dashboard or
deployed with `wrangler deploy` (worker/wrangler.toml points at the bundle).
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def main():
    with open(os.path.join(ROOT, "docs", "assets", "hl.js"), encoding="utf-8") as f:
        hl = f.read()
    with open(os.path.join(ROOT, "worker", "src", "worker.js"), encoding="utf-8") as f:
        worker = f.read()
    out = os.path.join(ROOT, "worker", "dist", "worker.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/build_worker.py; edit docs/assets/hl.js or worker/src/worker.js.\n")
        f.write(hl.rstrip() + "\n\n" + worker)
    print("wrote", os.path.relpath(out, ROOT), os.path.getsize(out))


if __name__ == "__main__":
    main()
